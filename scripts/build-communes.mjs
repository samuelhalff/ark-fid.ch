#!/usr/bin/env node
/**
 * Regenerates src/lib/tax-questionnaire/communes-data.ts (a JSON literal; a .ts module so that
 * the browser bundle, the server and node tests load it without JSON import attributes) from the Swiss Federal Statistical Office
 * (BFS/OFS) official commune register ("Amtliches Gemeindeverzeichnis / Répertoire officiel des
 * communes de Suisse"), through its public API:
 *   https://www.agvchapp.bfs.admin.ch/api/communes/snapshot?date=DD-MM-YYYY
 * (Level 1 = canton, 2 = district, 3 = commune; communes point to their district, districts to
 * their canton.) Run once a year (communes merge on 1 January):
 *   node scripts/build-communes.mjs [DD-MM-YYYY]   (default: 1 January of the current year)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src/lib/tax-questionnaire/communes-data.ts");
const date = process.argv[2] || `01-01-${new Date().getFullYear()}`;
if (!/^\d{2}-\d{2}-\d{4}$/.test(date)) throw new Error("Date must be DD-MM-YYYY");
const url = `https://www.agvchapp.bfs.admin.ch/api/communes/snapshot?date=${date}`;

const res = await fetch(url);
if (!res.ok) throw new Error(`BFS API ${res.status}`);
const lines = (await res.text()).trim().split(/\r?\n/);
const header = lines.shift().split(",");
const col = (name) => {
  const index = header.indexOf(name);
  if (index < 0) throw new Error(`Column ${name} missing (format changed?)`);
  return index;
};
const [iHist, iBfs, iLevel, iParent, iName, iShort] = ["HistoricalCode", "BfsCode", "Level", "Parent", "Name", "ShortName"].map(col);
const rows = lines.map((line) => {
  if (line.includes('"')) throw new Error("Quoted CSV not supported: check the file format");
  return line.split(",");
});
const cantons = new Map(rows.filter((r) => r[iLevel] === "1").map((r) => [r[iHist], r[iShort]]));
const districts = new Map(rows.filter((r) => r[iLevel] === "2").map((r) => [r[iHist], cantons.get(r[iParent])]));
const communes = rows
  .filter((r) => r[iLevel] === "3")
  .map((r) => [Number(r[iBfs]), r[iName], districts.get(r[iParent]) || cantons.get(r[iParent])])
  .filter(([bfs, name, canton]) => bfs > 0 && name && canton)
  .sort((a, b) => a[1].localeCompare(b[1], "fr"));
if (communes.length < 2000) throw new Error(`Only ${communes.length} communes: refusing to write`);

const json = JSON.stringify({ source: url, generatedOn: new Date().toISOString().slice(0, 10), communes }).replace(/\],\[/g, "],\n[");
fs.writeFileSync(
  OUT,
  "// Generated by scripts/build-communes.mjs from the BFS/OFS official commune register. Do not edit.\n" +
    "// communes: [BFS number, official name, canton]\n" +
    `export const COMMUNES_DATA: { source: string; generatedOn: string; communes: [number, string, string][] } = ${json};\n`,
);
console.log(`Wrote ${communes.length} communes (${date}) to ${path.relative(ROOT, OUT)}`);
